def _extract_general_10d_from_record(rec, study_ids=None):
    """High-fidelity rule-based Chinese 10-dimension PICO + 4W + MCID deconstructor for any clinical study record."""
    pmid = str(rec.get('pmid') or '').strip()
    if pmid in CURATED_PMID_CHARTING:
        return dict(CURATED_PMID_CHARTING[pmid])

    title = (rec.get('title') or '').strip()
    abstract = (rec.get('abstract') or '').strip()
    full_pages = (rec.get('fulltext') or {}).get('pages') or []
    full_text = '\n'.join(p.get('text', '') for p in full_pages)
    combined = f'{title}\n{abstract}\n{full_text}'
    low = combined.lower()

    # Check if any curated PMID or title substring matches
    for c_pmid, profile in CURATED_PMID_CHARTING.items():
        if c_pmid in combined:
            return dict(profile)

    # 1. Population & Sample size
    n_val = None
    for pat in (
        r'\b(?:enrolled|included|analyzed|recruited|comprising|total of)\s+([1-9]\d{1,5}(?:,\d{3})*)\s+(?:adult\s+|pediatric\s+|surgical\s+|postoperative\s+)?(?:patients|participants|women|children|infants|subjects|cases)\b',
        r'\b([1-9]\d{1,5}(?:,\d{3})*)\s+(?:adult\s+|pediatric\s+|surgical\s+|postoperative\s+)?(?:patients|participants|women|children|infants|subjects)\b',
        r'\b[Nn]\s*=\s*([1-9]\d{1,5}(?:,\d{3})*)\b',
    ):
        m = re.search(pat, combined, re.I)
        if m:
            n_val = m.group(1)
            break
    pop_group = '成人外科手术患者'
    if any(k in low for k in ('infant', 'neonat', 'newborn')):
        pop_group = '新生儿/婴儿外科手术患儿'
    elif any(k in low for k in ('children', 'pediatric', 'paediatric')):
        pop_group = '儿科外科手术患儿'
    elif any(k in low for k in ('geriatric', 'older', 'elderly')):
        pop_group = '老年外科手术患者'
    elif any(k in low for k in ('obstetric', 'cesarean', 'caesarean', 'postpartum')):
        pop_group = '产科剖宫产/分娩手术产妇'

    setting = '围术期及术后恢复病房'
    if 'pacu' in low or 'post-anesthesia care unit' in low:
        setting = '麻醉后监测治疗室（PACU）'
    elif 'nicu' in low:
        setting = '新生儿重症监护室（NICU）'
    elif 'home' in low or 'ambulatory' in low:
        setting = '日间手术院外居家恢复场景'
    population = f"{setting}{pop_group}（样本量 N = {n_val or '未单列'}）"

    # 2. Thematic axis & 4W Intervention
    if any(k in low for k in ('large language model', 'llm', 'chatgpt', 'gpt-4', 'gemini', 'copilot', 'ernie', 'natural language processing')):
        axis = '大语言模型与临床自然语言处理'
        what = '基于大语言模型（LLM）或临床自然语言处理（NLP）的围术期疼痛评估与决策支持系统'
        when = '术前宣教规划或术后病历文本评估阶段'
        how = '输入标准化围术期临床问题或电子病历自由文本，自动生成镇痛建议或提取疼痛相关文本特征'
        why = '利用预训练语言模型的语义理解与医学知识生成能力辅助医患沟通并识别临床镇痛偏倚'
    elif any(k in low for k in ('facial', 'video', 'action unit', 'camera', 'socially assistive robot', 'ultrasound', 'segmentation')):
        axis = '计算机视觉、面部动作单元与具身交互'
        what = '基于深度学习计算机视觉（面部动作单元/超声图像分割）或具身交互机器人的客观疼痛识别与导航系统'
        when = '术中实时导航或术后恢复期床旁连续视频监测阶段'
        how = '通过卷积神经网络或面部关键点算法自动编码面部表情动作单元与解剖特征，输出客观疼痛等级'
        why = '克服主观口头自评在苏醒期、婴幼儿或沟通障碍患者中的局限，通过非接触式视觉表征实现实时痛觉量化'
    elif any(k in low for k in ('closed-loop', 'analgesia nociception index', 'ani', 'nol', 'nociception level', 'surgical pleth index', 'spi', 'photoplethysmograph', 'ppg', 'wearable', 'biosignal', 'ecg', 'emg')):
        axis = '连续生理波形、可穿戴传感与闭环镇痛滴定'
        what = '基于多通道连续生理波形（PPG/ECG/EMG/HRV）或伤害性感受指数（NOL/ANI/SPI）的机器学习监测与闭环镇痛滴定系统'
