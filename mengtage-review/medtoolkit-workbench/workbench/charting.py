def validate_charting_entry(entry, record=None):
    """Validate a single study's 10-dimension charting dictionary."""
    if not isinstance(entry, dict):
        raise ValueError('数据提取条目须为字典对象')
    required = set(CHARTING_DIMENSIONS) | {'record_id', 'study_ids', 'locator', 'quote'}
    if set(entry) != required:
        missing = required - set(entry)
        extra = set(entry) - required
        raise ValueError(f'10维数据提取字段不完整或含多余字段（缺失：{missing}；多余：{extra}）')
    for dim in CHARTING_DIMENSIONS:
        val = entry[dim]
        if dim == 'intervention':
            if not isinstance(val, dict) or set(val) != set(INTERVENTION_4W_KEYS):
                raise ValueError('干预维度（intervention）须包含 what, when, how, why 四个子字段')
            for k in INTERVENTION_4W_KEYS:
                if not isinstance(val[k], str) or not 2 <= len(val[k].strip()) <= 2000:
                    raise ValueError(f'干预 4W 子字段 {k} 须为非空文本')
        else:
            if not isinstance(val, str) or not 2 <= len(val.strip()) <= 3000:
                raise ValueError(f'数据提取维度 {dim} 须为非空文本')
    if record is not None:
        validate_evidence(record, entry['locator'], entry['quote'])


def _call_configured_llm_charter(records_payload):
    """Optional external LLM 10-dimension PICO extractor when OPENAI_API_KEY / LLM_API_KEY is configured."""
    api_key = os.environ.get('OPENAI_API_KEY') or os.environ.get('LLM_API_KEY')
    api_base = (os.environ.get('OPENAI_BASE_URL') or os.environ.get('LLM_BASE_URL') or 'https://api.openai.com/v1').rstrip('/')
    model = os.environ.get('OPENAI_MODEL') or os.environ.get('LLM_MODEL') or 'gpt-4o-mini'
    if not api_key:
        return None
    prompt = (
        "你是医学系统综述数据提取专家。请针对以下每篇纳入文献提取完整中文10维PICO+MCID结构化矩阵。"
        "严禁直接复制英文原句或留空。返回JSON对象 {'charting': [...]}，每项包含："
        "record_id, population, intervention ({what, when, how, why}), comparator, outcomes, "
        "effect_size_and_mcid, reliability, authors_interpretation, advantages_and_limitations, "
        "innovations_and_value, thematic_axis。\n"
        f"文献列表：{json.dumps(records_payload, ensure_ascii=False)}"
    )
    body = {
        'model': model,
        'messages': [{'role': 'user', 'content': prompt}],
        'temperature': 0.1,
        'response_format': {'type': 'json_object'},
    }
    req = urllib.request.Request(
        f'{api_base}/chat/completions',
        data=json.dumps(body).encode('utf-8'),
        headers={'Content-Type': 'application/json', 'Authorization': f'Bearer {api_key}'},
        method='POST',
    )
    with urllib.request.urlopen(req, timeout=120) as resp:
        raw = resp.read().decode('utf-8')
    parsed = json.loads(raw)
    content = parsed['choices'][0]['message']['content']
    return json.loads(content).get('charting')


class DataChartingService:
    """Persistent, hash-chained 10-dimension PICO & methodological critique data charting service."""
    def __init__(self, service):
        self.service = service
        self.store = service.store
        with self.store.db() as db:
            db.execute('CREATE TABLE IF NOT EXISTS charting_events(sequence INTEGER PRIMARY KEY AUTOINCREMENT, review TEXT NOT NULL, event TEXT NOT NULL)')

    def events(self, review, db=None):
        if db is None:
            with self.store.db() as db:
                return self.events(review, db)
        rows = [json.loads(r[0]) for r in db.execute('SELECT event FROM charting_events WHERE review=? ORDER BY sequence', (review,))]
        previous = ''
        for event in rows:
            if event['previous_hash'] != previous or json_hash({k: v for k, v in event.items() if k != 'event_hash'}) != event['event_hash']:
                raise ValueError('10维数据提取审计链损坏')
            previous = event['event_hash']
        return rows

    def state(self, review, actor):
        study_state = self.service.studies.state(review, actor)
        if study_state['pending_final']:
            raise ValueError('请先完成全部全文裁决')
        if not study_state['mapping_valid']:
            raise ValueError('请先完成并确认报告—研究（Report-to-Study）实体映射')
        events = self.events(review)
        last = events[-1] if events else None
        valid = bool(
            last
            and last['screening_event_hash'] == study_state['screening_event_hash']
            and last['mapping_event_hash'] == study_state['mapping_event_hash']
        )
        return {
            'review': review,
            'screening_event_hash': study_state['screening_event_hash'],
            'mapping_event_hash': study_state['mapping_event_hash'],
            'charting_event_hash': last['event_hash'] if last else '',
            'charting_valid': valid,
            'records': study_state['records'],
            'mappings': study_state['mappings'],
            'charting': last['charting'] if valid else [],
            'history': events,
        }

    def extract(self, review, actor, mode='auto', save=False):
        if mode not in ('auto', 'structured', 'llm'):
            raise ValueError('数据提取模式仅支持 auto、structured 或 llm')
        st = self.state(review, actor)
        map_by_rid = {m['record_id']: m['study_ids'] for m in st['mappings']}
        rec_by_rid = {r['record_id']: r['record'] for r in st['records']}

        llm_entries = None
        if mode in ('auto', 'llm'):
            try:
                compact = [
                    {
                        'record_id': r['record_id'],
                        'pmid': r['record'].get('pmid', ''),
                        'title': r['record'].get('title', ''),
                        'abstract': r['record'].get('abstract', '')[:2000],
                    }
                    for r in st['records']
                ]
                llm_out = _call_configured_llm_charter(compact)
                if isinstance(llm_out, list):
                    llm_entries = {x['record_id']: x for x in llm_out if isinstance(x, dict) and 'record_id' in x}
            except Exception:
                if mode == 'llm':
                    raise ValueError('外部LLM 10维数据提取失败，请检查API配置或改用内置结构化提取器')

        charting_rows = []
        for r in st['records']:
            rid = r['record_id']
            rec = rec_by_rid[rid]
            sids = map_by_rid.get(rid, [rid])
            loc, quote = _find_verbatim_quote(rec)
            base_10d = _extract_general_10d_from_record(rec, sids)
            if llm_entries and rid in llm_entries:
                cand = llm_entries[rid]
                for dim in CHARTING_DIMENSIONS:
                    if dim == 'intervention' and isinstance(cand.get('intervention'), dict):
                        if all(isinstance(cand['intervention'].get(k), str) and cand['intervention'][k].strip() for k in INTERVENTION_4W_KEYS):
                            base_10d['intervention'] = {k: cand['intervention'][k].strip() for k in INTERVENTION_4W_KEYS}
                    elif isinstance(cand.get(dim), str) and cand[dim].strip():
                        base_10d[dim] = cand[dim].strip()
            entry = {
                'record_id': rid,
                'study_ids': sids,
                'locator': loc,
                'quote': quote,
                **base_10d,
            }
            validate_charting_entry(entry, rec)
            charting_rows.append(entry)

        if save is True:
            saved = self.save(
                review=review,
                actor=actor,
                charting=charting_rows,
                screening_event_hash=st['screening_event_hash'],
                mapping_event_hash=st['mapping_event_hash'],
                charting_event_hash=st['charting_event_hash'],
                confirmed=True,
            )
            return {'review': review, 'charting': charting_rows, 'saved': True, **saved}
        return {
            'review': review,
            'screening_event_hash': st['screening_event_hash'],
            'mapping_event_hash': st['mapping_event_hash'],
            'charting_event_hash': st['charting_event_hash'],
            'charting': charting_rows,
            'saved': False,
        }

    def save(self, review, actor, charting, screening_event_hash, mapping_event_hash, charting_event_hash='', confirmed=False):
        if confirmed is not True:
            raise ValueError('请确认10维临床证据数据提取表（Data Charting）')
        st = self.state(review, actor)
        if not isinstance(charting, list) or not charting:
            raise ValueError('需要非空的10维数据提取列表')
        rec_by_rid = {r['record_id']: r['record'] for r in st['records']}
        map_by_rid = {m['record_id']: m['study_ids'] for m in st['mappings']}
        seen = set()
        for row in charting:
            if not isinstance(row, dict) or 'record_id' not in row:
                raise ValueError('数据提取条目缺少record_id')
            rid = row['record_id']
            if rid not in rec_by_rid or rid in seen:
                raise ValueError('10维数据提取须覆盖每篇最终纳入报告且不可重复')
            seen.add(rid)
            validate_charting_entry(row, rec_by_rid[rid])
            if row['study_ids'] != map_by_rid[rid]:
                raise ValueError('数据提取中的研究ID须与当前已确认的研究映射一致')
        if seen != set(rec_by_rid):
            raise ValueError('不能遗漏任何已纳入报告的10维数据提取')

        with self.store.db() as db:
            db.execute('BEGIN IMMEDIATE')
            cur_st = self.state(review, actor)
            if cur_st['screening_event_hash'] != screening_event_hash or cur_st['mapping_event_hash'] != mapping_event_hash:
                raise ValueError('全文裁决或研究映射已变化，请刷新后重新核对')
            events = self.events(review, db)
            if (events[-1]['event_hash'] if events else '') != charting_event_hash:
                raise ValueError('10维数据提取表已有新版本，请刷新后再修订')
            event = {
                'event_id': uuid.uuid4().hex,
                'review_id': review,
                'actor': actor,
                'timestamp': now(),
                'screening_event_hash': screening_event_hash,
                'mapping_event_hash': mapping_event_hash,
                'charting': charting,
                'previous_hash': charting_event_hash,
                'schema': 'medtoolkit-10d-pico-charting-v1',
            }
            event['event_hash'] = json_hash(event)
            db.execute('INSERT INTO charting_events(review,event) VALUES(?,?)', (review, canonical(event)))
        return {'event_hash': event['event_hash'], 'charted_count': len(charting)}
