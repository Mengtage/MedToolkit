    # 3. Comparator & 6. Reliability
    is_rct = any(k in low for k in ('randomized', 'randomised', 'rct'))
    is_ext = any(k in low for k in ('external validation', 'externally validated', 'two hospitals', 'two university hospitals', 'multicenter'))
    is_blind = 'double-blind' in low or 'single-blind' in low or 'blinded' in low
    trial_m = re.search(r'\b(NCT\d{6,10}|ChiCTR[A-Za-z0-9-]{5,18}|KCT\d{6,10}|ISRCTN\d{6,10})\b', combined, re.I)
    trial_str = f"，注册号 {trial_m.group(1).upper()}" if trial_m else ""

