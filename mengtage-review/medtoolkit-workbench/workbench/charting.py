    auc_m = re.search(r'\b(?:AUROC|AUC)\s*(?:of|=|:|\(|was|reached)?\s*(0\.\d{2,3})', combined, re.I)
    if auc_m:
        eff_parts.append(f"模型预测区分度 AUROC = {auc_m.group(1)}")
    brier_m = re.search(r'\bBrier(?:\s+score)?\s*(?:of|=|:|\(|was)?\s*(0\.\d{2,4})', combined, re.I)
